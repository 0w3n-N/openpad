#!/usr/bin/env python3
"""Merge test vectors for other implementations of openpad/notebook.py.

Writes ios/OpenPadCore/Tests/OpenPadCoreTests/Resources/merge_vectors.json:
pairs of edited copies of a notebook and what merging them must give. The
iPad app's Swift tests load it; tests/run.py checks the file is current.

    python3 -B tests/make_vectors.py
"""

from __future__ import annotations

import copy
import json
import os
import random
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from openpad import notebook as N  # noqa: E402

OUT = os.path.join(ROOT, "ios", "OpenPadCore", "Tests", "OpenPadCoreTests", "Resources", "merge_vectors.json")


def build(seed=11, count=40):
    rng = random.Random(seed)
    ids = iter(f"{i:012x}" for i in range(1, 10 ** 9))
    t0 = 1_790_000_000_000

    def stroke():
        return N.clean_stroke({"id": next(ids), "z": t0 * 1000 + rng.randint(0, 10 ** 6), "tool": rng.choice(N.TOOLS),
                               "color": rng.choice(["#111111", "#1f5fd6", "#d62f2f"]), "width": rng.choice([2, 3.5, 6.5]),
                               "pts": [[rng.randint(0, 999) + 0.25, rng.randint(0, 1200) + 0.5, round(rng.random(), 3)]
                                       for _ in range(rng.randint(1, 6))]})

    def page(sec, t):
        return {"id": next(ids), "t": t, "sec": sec, "w": 1000, "h": 1294.12, "paper": "lines", "bg": None,
                "pt": [612, 792], "strokes": [], "gone": []}

    cases = []
    for _ in range(count):
        sec = next(ids)
        pages = [page(sec, t0) for _ in range(rng.randint(1, 3))]
        base = N.finish({"v": 1, "id": next(ids), "title": "Physics", "size": "letter", "metaT": t0, "created": t0,
                         "layout": {"t": t0, "sections": [{"id": sec, "title": "Lecture 1", "pages": [p["id"] for p in pages]}]},
                         "goneP": [], "pages": {p["id"]: p for p in pages}})
        sides = [copy.deepcopy(base), copy.deepcopy(base)]
        for side in sides:
            for _ in range(rng.randint(0, 7)):
                order = N.order(side)
                pg = side["pages"][rng.choice(order)]
                op = rng.random()
                if op < 0.45:
                    pg["strokes"].append(stroke())
                elif op < 0.6 and pg["strokes"]:
                    s = rng.choice(pg["strokes"])
                    pg["strokes"].remove(s)
                    pg["gone"] = sorted(set(pg["gone"]) | {s["id"]})
                elif op < 0.7:
                    pg.update(paper=rng.choice(N.PAPERS), t=pg["t"] + rng.randint(1, 9))
                elif op < 0.78:
                    pg.update(bg=rng.choice([{"pdf": "ab" * 32, "n": rng.randint(1, 4)}, {"img": "cd" * 32}, None]),
                              t=pg["t"] + rng.randint(1, 9))
                elif op < 0.86:
                    side.update(title=rng.choice(["Physics", "Physik", "Waves"]), metaT=side["metaT"] + rng.randint(0, 3))
                elif op < 0.94:
                    np_ = page(rng.choice([s["id"] for s in side["layout"]["sections"]]), t0 + rng.randint(0, 99))
                    side["pages"][np_["id"]] = np_
                    secs = [dict(s, pages=list(s["pages"])) for s in side["layout"]["sections"]]
                    target = next(s for s in secs if s["id"] == np_["sec"])
                    target["pages"].append(np_["id"])
                    side["layout"] = {"t": side["layout"]["t"] + rng.randint(1, 9), "sections": secs}
                elif len(order) > 1:
                    gone = rng.choice(order)
                    side["goneP"] = sorted(set(side["goneP"]) | {gone})
                    secs = [dict(s, pages=[x for x in s["pages"] if x != gone]) for s in side["layout"]["sections"]]
                    side["layout"] = {"t": side["layout"]["t"] + rng.randint(1, 9), "sections": secs}
                    N.finish(side)
        a, b = sides
        m = N.merge(copy.deepcopy(a), copy.deepcopy(b))
        cases.append({
            "a": a,
            "b": b,
            "expect": {
                "digest": N.digest(m),
                "order": N.order(m),
                "title": m["title"],
                "goneP": m["goneP"],
                "pages": {pid: {"strokes": [s["id"] for s in p["strokes"]], "gone": p["gone"], "paper": p["paper"],
                                "bg": p["bg"], "t": p["t"]} for pid, p in m["pages"].items()},
            },
        })
    return {"about": "Generated by tests/make_vectors.py from openpad/notebook.py. Do not edit.", "cases": cases}


def text():
    return json.dumps(build(), indent=1, sort_keys=True) + "\n"


if __name__ == "__main__":
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write(text())
    print(f"wrote {OUT}")
